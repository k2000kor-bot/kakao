/**
 * 도메인 간 관계 그래프 데이터
 */
export interface DomainRelationGraph {
  nodes: {
    id: string;
    label: string;
    group: string;
    value: number;
  }[];
  links: {
    source: string;
    target: string;
    value: number;
    label?: string;
  }[];
}

export function getDomainRelationGraph(): DomainRelationGraph {
  const nodes = Object.keys(DOMAIN_KNOWLEDGE_BASE).map(domainKey => ({
    id: domainKey,
    label: domainKey,
    group: domainKey,
    value: DOMAIN_KNOWLEDGE_BASE[domainKey].concepts.length,
  }));

  const domainRelations: Record<string, string[]> = {
    '도시정비': ['국토부', '부동산정책', '법무', '건축법', '감정평가'],
    '세무': ['법무', '부동산정책', '회계'],
    '법무': ['세무', '부동산중개', '대법원판례', '계약', '형사'],
    '금융': ['부동산정책', '세무', '회계'],
    '국토부': ['도시정비', '부동산정책', '건축법'],
    '부동산정책': ['국토부', '세무', '금융'],
    '대법원판례': ['법무', '부동산중개'],
    '부동산중개': ['법무', '대법원판례', '감정평가'],
    '건축법': ['국토부', '도시정비', '서울시행정'],
    '서울시행정': ['건축법', '도시정비'],
    '형사': ['법무'],
    '계약': ['법무', '대법원판례'],
    '회계': ['세무', '금융'],
    '감정평가': ['도시정비', '부동산중개', '세무']
  };

  const links: DomainRelationGraph['links'] = [];
  for (const [source, targets] of Object.entries(domainRelations)) {
    for (const target of targets) {
      links.push({
        source,
        target,
        value: 1,
        label: '관련',
      });
    }
  }

  return { nodes, links };
}

