/**
 * 도메인 지식 검증 및 품질 관리
 */
export interface KnowledgeQuality {
  domain: string;
  completeness: number; // 0-100
  accuracy: number; // 0-100
  relevance: number; // 0-100
  lastUpdated: string;
  issues: string[];
}

export function validateDomainKnowledge(domainKey: string): KnowledgeQuality {
  const key = resolveDomainKey(domainKey);
  const domain = DOMAIN_KNOWLEDGE_BASE[key];
  if (!domain) {
    return {
      domain: key,
      completeness: 0,
      accuracy: 100,
      relevance: 0,
      lastUpdated: new Date().toISOString(),
      issues: ['도메인을 찾을 수 없습니다']
    };
  }

  const issues: string[] = [];
  let completeness = 100;

  // 완전성 검증
  if (domain.laws.length === 0) {
    issues.push('주요 법령이 없습니다');
    completeness -= 20;
  }
  if (domain.concepts.length < 5) {
    issues.push('핵심 개념이 부족합니다');
    completeness -= 10;
  }
  if (!domain.procedures || domain.procedures.length === 0) {
    issues.push('절차 정보가 없습니다');
    completeness -= 15;
  }

  return {
    domain: key,
    completeness: Math.max(0, completeness),
    accuracy: 95, // 기본값
    relevance: 90, // 기본값
    lastUpdated: new Date().toISOString(),
    issues
  };
}

