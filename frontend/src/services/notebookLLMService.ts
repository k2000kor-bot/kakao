export function buildResponseFormatInstructions(prompt: string): string {
  const lower = prompt.toLowerCase();
  const parts: string[] = [];
  for (const { keywords, instruction } of FORMAT_PATTERNS) {
    if (keywords.some(k => lower.includes(k))) {
      parts.push(instruction);
      break;
    }
  }
  for (const { keywords, instruction } of EXPERT_VIEW_PATTERNS) {
    if (keywords.some(k => lower.includes(k))) {
      parts.push(instruction);
      break;
    }
  }
  return parts.join('');
}

/**
 * 도메인 지식 검색
 */
export interface DomainSearchResult {
  domain: string;
  matches: {
    type: 'law' | 'concept' | 'procedure' | 'calculation' | 'policy' | 'case';
    content: string;
    relevance: number;
  }[];
  totalMatches: number;
}

export function searchDomainKnowledge(query: string, domainFilter?: string[]): DomainSearchResult[] {
  const queryLower = query.toLowerCase();
  const results: DomainSearchResult[] = [];
  const resolvedFilter = resolveDomainFilter(domainFilter);
  const domainsToSearch = resolvedFilter || Object.keys(DOMAIN_KNOWLEDGE_BASE);

  for (const domainKey of domainsToSearch) {
    const domain = DOMAIN_KNOWLEDGE_BASE[domainKey];
    if (!domain) continue;

    const matches: DomainSearchResult['matches'] = [];

    // 법령 검색
    for (const law of domain.laws) {
      if (law.toLowerCase().includes(queryLower)) {
        matches.push({
          type: 'law',
          content: law,
          relevance: 3,
        });
      }
    }

    // 개념 검색
    for (const concept of domain.concepts) {
      if (concept.toLowerCase().includes(queryLower)) {
        matches.push({
          type: 'concept',
          content: concept,
          relevance: 2,
        });
      }
    }

    // 절차 검색
    if (domain.procedures) {
      for (const procedure of domain.procedures) {
        if (procedure.toLowerCase().includes(queryLower)) {
          matches.push({
            type: 'procedure',
            content: procedure,
            relevance: 1.5,
          });
        }
      }
    }

    // 계산방법 검색
    if (domain.calculations) {
      for (const calc of domain.calculations) {
        if (calc.toLowerCase().includes(queryLower)) {
          matches.push({
            type: 'calculation',
            content: calc,
            relevance: 2.5,
          });
        }
      }
    }

    // 정책 검색
    if (domain.policies) {
      for (const policy of domain.policies) {
        if (policy.toLowerCase().includes(queryLower)) {
          matches.push({
            type: 'policy',
            content: policy,
            relevance: 2,
          });
        }
      }
    }

    // 판례 검색
    if (domain.cases) {
      for (const case_principle of domain.cases) {
        if (case_principle.toLowerCase().includes(queryLower)) {
          matches.push({
            type: 'case',
            content: case_principle,
            relevance: 2.5,
          });
        }
      }
    }

    if (matches.length > 0) {
      // 관련도 순으로 정렬
      matches.sort((a, b) => b.relevance - a.relevance);

      results.push({
        domain: domainKey,
        matches,
        totalMatches: matches.length,
      });
    }
  }

  // 매칭 수가 많은 순으로 정렬
  results.sort((a, b) => b.totalMatches - a.totalMatches);

  return results;
}

